def save_case(id,language,source,source_id,original_bytes,reference,annotation_path,metadata):
    raw_path=OUT/'source-images'/(id+('.tif' if source=='rimes' else '.jpg'))
    raw_path.write_bytes(original_bytes)
    image=Image.open(io.BytesIO(original_bytes)).convert('RGB')
    original_size=list(image.size)
    image.save(OUT/'images'/(id+'.png'))
    if metadata.get('excluded_signature_boxes'):
        # Keep the real full-page layout; remove only source-defined signatures
        # that have no published text reference. Never fabricate a signature GT.
        draw=ImageDraw.Draw(image)
        sw,sh=metadata['annotation_source_size']
        for box in metadata['excluded_signature_boxes']:
            x1,y1,x2,y2=box
            draw.rectangle((round(x1*image.width/sw),round(y1*image.height/sh),round(x2*image.width/sw),round(y2*image.height/sh)),fill='white')
    image.thumbnail((1024,1024),Image.Resampling.BICUBIC)
    image.save(OUT/'images-modele'/(id+'.png'))
    (OUT/'ground-truth'/(id+'.txt')).write_text(reference,encoding='utf-8')
    dest=OUT/'annotations'/(id+'.xml');shutil.copyfile(annotation_path,dest)
    return {'id':id,'language':language,'source':source,'source_id':source_id,
        'image':'images/'+id+'.png','image_sha256':sha((OUT/'images'/(id+'.png')).read_bytes()),'image_size':original_size,
        'inference_image':'images-modele/'+id+'.png','inference_image_sha256':sha((OUT/'images-modele'/(id+'.png')).read_bytes()),'inference_size':list(image.size),
        'ground_truth':'ground-truth/'+id+'.txt','ground_truth_sha256':sha((OUT/'ground-truth'/(id+'.txt')).read_bytes()),
        'annotation':'annotations/'+id+'.xml','annotation_sha256':sha(dest.read_bytes()),'original_download_sha256':sha(original_bytes),
        'reference_origin':'published human transcription, not generated by either compared OCR',
        'is_real_handwriting':True,'synthetic_layout':False,'source_reference':reference,**metadata}

def arabic():
    with (S/'rasam-list.txt').open(encoding='utf-8',newline='') as f:rows=list(csv.DictReader(f,delimiter='\t'))
    index={r['FileName']:r for r in rows if r.get('FileName')}
    def one(item):
        number,(source_id,layout)=item
        path=S/'rasam-annotations'/(source_id+'.xml');root=ET.parse(path).getroot()
        page=next(e for e in root.iter() if local(e.tag)=='Page')
        regions=[e for e in page.iter() if local(e.tag)=='TextRegion']
        lines=[e for e in page.iter() if local(e.tag)=='TextLine']
        texts=[]
        for line in lines:
            unicode=next((e.text or '' for e in line.iter() if local(e.tag)=='Unicode'),'').strip()
            assert unicode,source_id+' has an untranscribed annotated line'
            texts.append(unicode)
        record=index[source_id];image_id=record['IIIF image ID']
        url='https://bina.bulac.fr/iiif/2/'+image_id+'/full/!1800,1800/0/default.jpg'
        original=S/'rasam-images'/(source_id+'.jpg');original.parent.mkdir(exist_ok=True)
        if not original.exists():
            # Windows Schannel completes the public source's issuer chain.
            # Certificate and hostname validation remain enabled; no -k flag.
            response=subprocess.run(['curl.exe','--fail','--location','--silent','--show-error','--max-time','85','--output',str(original),url],capture_output=True,text=True)
            if response.returncode:raise RuntimeError('Verified public image download failed: '+source_id)
        result=save_case(f'ar-{number:02d}','ar','rasam1',source_id,original.read_bytes(),'\n'.join(texts),path,
            {'layout':layout,'regions':len(regions),'lines':len(lines),'document_id':source_id.rsplit('_',1)[0],
             'image_url':url,'source_url':'https://github.com/calfa-co/rasam-dataset','license':'Apache-2.0, with image rights of BULAC',
             'reference_processing':'TextLine Unicode in source PAGE XML order; no spelling or digit normalization'})
        print('PREPARED',result['id'],source_id,len(result['source_reference']),flush=True);return result
    with concurrent.futures.ThreadPoolExecutor(max_workers=5) as pool:return list(pool.map(one,enumerate(AR,1)))

def zipped(source):
    key='Images_Courriers.zip' if source=='rimes' else 'revcity-htr.zip'
    rec='rimes-record.json' if source=='rimes' else 'rev-city-record.json'
    data=json.loads((S/rec).read_text());file=next(x for x in data['files'] if x['key']==key)
    members=json.loads((S/'rimes-selected.json').read_text())['selected'] if source=='rimes' else ['data/'+id+'.xml' for id,_ in EN]
    language='fr' if source=='rimes' else 'en';cases=[]
    with zipfile.ZipFile(RemoteZipFile(file['links']['self'],file['size'])) as z:
        for n,member in enumerate(members,1):
            base=Path(member).stem;path=S/(source+'-annotations')/(base+'.xml');root=ET.parse(path).getroot()
            if source=='rimes':
                boxes=root.findall('box');texts=[(b.findtext('text') or '').replace('\\n','\n').strip() for b in boxes]
                reference='\n\n'.join(t for t in texts if t)
                assert '¤' not in reference and len(reference)>200
                meta={'layout':'Lettre avec '+str(len(boxes))+' blocs : adresses, objet ou date, corps et signature',
                    'regions':len(boxes),'document_id':'RIMES-'+base,
                    'reference_processing':'Nonempty source box text in XML order; literal \\n decoded; ambiguous alternatives excluded before inference',
                    'untranscribed_regions':[b.findtext('type') for b in boxes if not (b.findtext('text') or '').strip()],
                    'signature_limit':'Untranscribed signature regions whitened identically for both models; this does not evaluate signature recognition',
                    'annotation_source_size':[int(root.find('source').attrib['width']),int(root.find('source').attrib['height'])],
                    'excluded_signature_boxes':[[int(b.attrib[k]) for k in ('top_left_x','top_left_y','bottom_right_x','bottom_right_y')] for b in boxes if b.findtext('type')=='Signature' and not (b.findtext('text') or '').strip()],
                    'source_url':'https://zenodo.org/records/10812725','license':data['metadata'].get('license',{})}
                image_member=member[:-4]+'.tif'
            else:
                lines=[e for e in root.iter() if local(e.tag)=='TextLine'];texts=[]
                for line in lines:
                    parts=[e.attrib.get('CONTENT','') for e in line.iter() if local(e.tag) in ('String','HYP')]
                    text=' '.join(parts).strip()
                    if text:texts.append(text)
                # Superscript prefix is an editorial convention, not a drawn caret.
                reference='\n'.join(texts).replace('^','')
                assert reference and '[___]' not in reference
                meta={'layout':EN[n-1][1],'regions':sum(local(e.tag)=='TextBlock' for e in root.iter()),'lines':len(texts),
                    'document_id':base,'source_url':'https://zenodo.org/records/15776323','license':'CC-BY-4.0',
                    'reference_processing':'ALTO TextLine String CONTENT in source order; editorial superscript prefix ^ removed; abbreviations retained',
                    'document_independence':'Separate image IDs do not establish distinct writers or historical documents'}
                image_member=member[:-4]+'.jpg'
            original=S/(source+'-images')/Path(image_member).name;original.parent.mkdir(exist_ok=True)
            if not original.exists():original.write_bytes(z.read(image_member))
            result=save_case(f'{language}-{n:02d}',language,source,base,original.read_bytes(),reference,path,
                            {**meta,'archive_member':image_member,'archive_record':data['id']})
            cases.append(result);print('PREPARED',result['id'],base,len(reference),flush=True)
    return cases

def main():
    for name in ('source-images','images','images-modele','ground-truth','annotations'):(OUT/name).mkdir(parents=True,exist_ok=True)
    with concurrent.futures.ThreadPoolExecutor(max_workers=3) as pool:
        tasks=[pool.submit(arabic),pool.submit(zipped,'rimes'),pool.submit(zipped,'rev-city')]
        cases=[c for t in tasks for c in t.result()]
    cases.sort(key=lambda c:({'ar':0,'fr':1,'en':2}[c['language']],c['id']))
    assert len(cases)==31
    manifest={'schema':1,'created_at_utc':datetime.now(timezone.utc).isoformat(),'counts':{'ar':15,'fr':8,'en':8},
        'preprocessing':'Real full pages, RGB PNG; nontranscribed RIMES signature boxes whitened; aspect-preserving BICUBIC thumbnail at 1024 pixels for both models',
        'real_handwritten_pages':31,'font_generated_pages':0,'collages':0,'references_sent_to_models':False,
        'selection_before_inference':True,'inspection_status':'pending image/reference correspondence review before inference',
        'selection':'Five fully annotated RASAM1 pages from each of three manuscripts; eight RIMES letters without ambiguous alternatives selected with seed 20261029; eight English historical layouts selected by annotations',
        'cases':cases}
    (OUT/'jeu.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2),encoding='utf-8')
    print('DATASET_PREPARED_REAL_31_PAGES',flush=True)

if __name__=='__main__':main()
